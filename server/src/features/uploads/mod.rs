/// Bounded part size configuration.
pub const PART_SIZE: i64 = 16 * 1024 * 1024;
/// Upload parameters; initial display names are always generated by the server.
#[derive(Deserialize, ToSchema)]
#[serde(deny_unknown_fields)]
pub struct CreateUpload {
    /// Optional explicit album membership; absent means standalone.
    pub album_id: Option<String>,
    /// Expected or validated object length in bytes.
    pub size: i64,
    /// Requested public or private access policy.
    pub visibility: String,
    /// Container extension, independent of the randomized display name.
    #[serde(default = "default_extension")]
    pub extension: String,
    /// Browser-probed display width; zero means unavailable.
    #[serde(default)]
    pub width: i64,
    /// Browser-probed display height; zero means unavailable.
    #[serde(default)]
    pub height: i64,
    /// Browser-probed duration in seconds; zero means unavailable.
    #[serde(default)]
    pub duration: f64,
}
/// Safe upload limits exposed without credentials or storage configuration.
#[derive(Serialize, ToSchema)]
pub struct UploadPolicy {
    /// Maximum accepted video length in bytes.
    pub max_upload_bytes: i64,
    /// Independent maximum original-image length in bytes.
    pub max_image_upload_bytes: i64,
    /// Enabled lowercase container extensions.
    pub allowed_extensions: Vec<String>,
    /// Image containers used by clients to choose image metadata and preview generation.
    pub image_extensions: Vec<String>,
}
/// Retain the existing container name for legacy clients that omit an extension.
fn default_extension() -> String {
    "mp4".into()
}
/// Return environment-configured limits for the authenticated upload interface.
///
/// # Errors
/// Returns authentication or database errors.
#[utoipa::path(get, path = "/v1/admin/upload-policy", responses((status = 200, body = UploadPolicy)), security(("session" = [])))]
pub async fn policy(State(s): State<AppState>, _admin: Admin) -> Result<Json<UploadPolicy>> {
    let mut allowed_extensions = s.config.video_extensions.clone();
    allowed_extensions.extend(s.config.image_extensions.iter().cloned());
    Ok(Json(UploadPolicy {
        max_upload_bytes: s.config.max_upload_bytes,
        max_image_upload_bytes: s.config.max_image_upload_bytes,
        allowed_extensions,
        image_extensions: s.config.image_extensions.clone(),
    }))
}
/// S3-confirmed part metadata used to resume an interrupted upload.
#[derive(Serialize, ToSchema)]
pub struct UploadedPart {
    /// One-based S3 multipart part number.
    pub number: i32,
    /// Expected or validated object length in bytes.
    pub size: i64,
    /// Base64 SHA-256 checksum of a single uploaded part.
    #[schema(required = true)]
    pub checksum: Option<String>,
}
/// Resumable upload details with the server-assigned display hash.
#[derive(Serialize, ToSchema)]
pub struct Upload {
    /// Stable internal identifier for this record.
    pub id: String,
    /// Identifier of the associated video record.
    pub video_id: String,
    /// Display name; uploads receive a fresh server-generated hash.
    pub name: String,
    /// Planned non-final part size in bytes.
    pub part_size: i64,
    /// Number of parts required by the declared file size.
    pub part_count: i32,
    /// Absolute expiry timestamp in Unix seconds.
    pub expires_at: i64,
    /// Verified uploaded parts available for resumable transfer.
    pub parts: Vec<UploadedPart>,
}
/// Durable multipart session linked to its internal video record.
#[derive(FromRow)]
struct Record {
    /// Opaque upload session identifier.
    id: String,
    /// Associated internal video identifier.
    video_id: String,
    /// S3 multipart upload identifier.
    upload_id: String,
    /// Absolute session expiry in Unix seconds.
    expires_at: i64,
    /// Persisted multipart lifecycle state.
    state: String,
}
/// Checksum required to authorize a single multipart part.
#[derive(Deserialize, ToSchema)]
pub struct PartInput {
    /// Base64 SHA-256 checksum of a single uploaded part.
    pub checksum: String,
}
/// Temporary S3 upload authorization scoped to one numbered part.
#[derive(Serialize, ToSchema)]
pub struct PartUrl {
    /// Short-lived presigned URL scoped to one upload part.
    pub url: String,
}
/// Load the durable multipart session without exposing its S3 credentials.
///
/// # Errors
/// Returns 404 for an unknown upload, or a database error.
async fn record(s: &AppState, id: &str) -> Result<Record> {
    sqlx::query_as("SELECT * FROM uploads WHERE id=?")
        .bind(id)
        .fetch_optional(&s.db)
        .await?
        .ok_or_else(missing)
}
/// Validate original-file policy independently of reserving a durable multipart session.
///
/// # Errors
/// Returns invalid size, visibility, container, or presentation metadata errors.
fn validate_input(s: &AppState, input: &CreateUpload) -> Result<MediaKind> {
    let kind = if s.config.image_extensions.contains(&input.extension) {
        MediaKind::Image
    } else if s.config.video_extensions.contains(&input.extension) {
        MediaKind::Video
    } else {
        return Err(bad("Unsupported media extension"));
    };
    let limit = match kind {
        MediaKind::Image => s.config.max_image_upload_bytes,
        MediaKind::Video => s.config.max_upload_bytes,
    };
    if input.size < 16 || input.size > limit {
        return Err(bad("Media exceeds its configured size limit"));
    }
    if !matches!(input.visibility.as_str(), "private" | "public") {
        return Err(bad("Invalid visibility"));
    }
    if !(0..=32768).contains(&input.width)
        || !(0..=32768).contains(&input.height)
        || !input.duration.is_finite()
        || !(0.0..=31_536_000.0).contains(&input.duration)
    {
        return Err(bad("Unsupported extension or invalid media dimensions"));
    }
    Ok(kind)
}
/// Create a private multipart session with independent random name and URL token.
///
/// # Errors
/// Returns authentication, CSRF, upload-limit, membership, delivery, S3, or database errors.
#[utoipa::path(
    post,
    path = "/v1/admin/uploads",
    request_body = CreateUpload,
    responses((status = 201, body = Upload)),
    security(("session" = [])),
)]
pub async fn create(
    State(s): State<AppState>,
    _admin: Admin,
    Json(input): Json<CreateUpload>,
) -> Result<(StatusCode, Json<Upload>)> {
    let storage = s.storage.get()?;
    let kind = validate_input(&s, &input)?;
    let name = random_id();
    let video_id = random_id();
    let token = random_id();
    let source_key = Storage::private(&token, &input.extension);
    let poster_key = Storage::private_preview(&token);
    let id = random_id();
    let expires_at = now() + 86400;
    // Reserve a slot transactionally before opening an S3 upload.
    let mut tx = s.db.begin_with("BEGIN IMMEDIATE").await?;
    let prefix = videos::album_prefix(&mut tx, input.album_id.as_deref()).await?;
    let count: i64 =
        sqlx::query_scalar("SELECT COUNT(*) FROM videos WHERE state IN ('uploading','verifying')")
            .fetch_one(&mut *tx)
            .await?;
    if count >= 4 {
        return Err(Error(
            StatusCode::TOO_MANY_REQUESTS,
            "At most four unfinished uploads are allowed",
        ));
    }
    sqlx::query(
        r"INSERT INTO videos(id, token, album_id, name, visibility, state, size,
created_at,extension,width,height,duration,media_prefix,source_key,poster_key,kind) VALUES(?, ?, ?, ?, ?, 'uploading', ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
    )
    .bind(&video_id)
    .bind(token)
    .bind(input.album_id)
    .bind(&name)
    .bind(input.visibility)
    .bind(input.size)
    .bind(now())
    .bind(input.extension)
    .bind(input.width)
    .bind(input.height)
    .bind(input.duration)
    .bind(&prefix)
    .bind(&source_key)
    .bind(&poster_key)
    .bind(kind)
    .execute(&mut *tx)
    .await?;
    sqlx::query("INSERT INTO media_aliases(video_id,prefix) VALUES(?,?)")
        .bind(&video_id)
        .bind(prefix)
        .execute(&mut *tx)
        .await?;
    tx.commit().await?;
    let upload_id = match storage.begin(&source_key).await {
        Ok(v) => v,
        Err(e) => {
            sqlx::query("UPDATE videos SET state='failed' WHERE id=?")
                .bind(&video_id)
                .execute(&s.db)
                .await?;
            return Err(e.into());
        }
    };
    if let Err(e) =
        sqlx::query("INSERT INTO uploads(id,video_id,upload_id,expires_at) VALUES(?,?,?,?)")
            .bind(&id)
            .bind(&video_id)
            .bind(&upload_id)
            .bind(expires_at)
            .execute(&s.db)
            .await
    {
        let _ = storage.abort(&source_key, &upload_id).await;
        return Err(e.into());
    }
    Ok((
        StatusCode::CREATED,
        Json(Upload {
            id,
            video_id,
            name,
            part_size: PART_SIZE,
            part_count: i32::try_from((input.size + PART_SIZE - 1) / PART_SIZE)
                .map_err(|_| bad("Too many upload parts"))?,
            expires_at,
            parts: Vec::new(),
        }),
    ))
}
/// Issue a short-lived signature for one checksummed multipart part.
///
/// # Errors
/// Returns authentication, CSRF, checksum, part-number, expired-session, S3, or database errors.
#[utoipa::path(
    post,
    path = "/v1/admin/uploads/{id}/parts/{part}",
    params(("id" = String, Path), ("part" = i32, Path)),
    request_body = PartInput,
    responses((status = 200, body = PartUrl)),
    security(("session" = [])),
)]
pub async fn part(
    State(s): State<AppState>,
    _admin: Admin,
    Path((id, part)): Path<(String, i32)>,
    Json(input): Json<PartInput>,
) -> Result<Json<PartUrl>> {
    let r = record(&s, &id).await?;
    if input.checksum.len() != 44
        || !input
            .checksum
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b"+/=".contains(&b))
    {
        return Err(bad("Expected base64 SHA-256 checksum"));
    }
    if r.state != "uploading" || r.expires_at <= now() {
        return Err(bad("Upload expired or no longer accepts parts"));
    }
    let v = videos::get(&s, &r.video_id).await?;
    if part < 1 || i64::from(part) > (v.size + PART_SIZE - 1) / PART_SIZE {
        return Err(bad("Invalid part number"));
    }
    Ok(Json(PartUrl {
        url: s
            .storage
            .get()?
            .part(&v.private_source(), &r.upload_id, part, &input.checksum)
            .await?,
    }))
}
/// Validate multipart state and schedule verification or complete the S3 object.
///
/// # Errors
/// Returns authentication, CSRF, expired-session, state-conflict, or database errors.
#[utoipa::path(
    post,
    path = "/v1/admin/uploads/{id}/complete",
    params(("id" = String, Path)),
    responses((status = 202, body = Accepted)),
    security(("session" = [])),
)]
pub async fn complete(
    State(s): State<AppState>,
    _admin: Admin,
    Path(id): Path<String>,
) -> Result<(StatusCode, Json<Accepted>)> {
    let r = record(&s, &id).await?;
    let _transition = s.upload_lifecycle.lock(&r.video_id).await;
    let r = record(&s, &id).await?;
    if r.state == "complete" {
        return Ok((StatusCode::ACCEPTED, Json(Accepted { job_id: None })));
    }
    if r.expires_at <= now() {
        return Err(bad("Upload expired"));
    }
    let job = random_id();
    let mut tx = s.db.begin().await?;
    let changed =
        sqlx::query("UPDATE uploads SET state='verifying' WHERE id=? AND state='uploading'")
            .bind(&id)
            .execute(&mut *tx)
            .await?
            .rows_affected();
    if changed == 0 {
        return Err(Error(
            StatusCode::CONFLICT,
            "Completion is already in progress",
        ));
    }
    sqlx::query("UPDATE videos SET state='verifying' WHERE id=?")
        .bind(&r.video_id)
        .execute(&mut *tx)
        .await?;
    sqlx::query("INSERT INTO jobs(id,video_id,kind,revision,created_at) VALUES(?,?,'verify',0,?)")
        .bind(&job)
        .bind(&r.video_id)
        .bind(now())
        .execute(&mut *tx)
        .await?;
    tx.commit().await?;
    s.job_wakeup.notify_one();
    Ok((StatusCode::ACCEPTED, Json(Accepted { job_id: Some(job) })))
}
/// Serve or store a bounded authenticated JPEG poster.
///
/// # Errors
/// Returns authentication, CSRF, state-conflict, JPEG-limit, S3, or database errors.
#[utoipa::path(
    put,
    path = "/v1/admin/videos/{id}/poster",
    params(("id" = String, Path)),
    request_body(content = inline(crate::http::schema::BinaryBody), content_type = "image/jpeg"),
    responses((status = 204, description = "Poster saved")),
    security(("session" = [])),
)]
pub async fn poster(
    State(s): State<AppState>,
    _admin: Admin,
    Path(id): Path<String>,
    body: Bytes,
) -> Result<StatusCode> {
    let _transition = s.upload_lifecycle.lock(&id).await;
    let v = videos::get(&s, &id).await?;
    if v.state != "uploading" {
        return Err(Error(
            StatusCode::CONFLICT,
            "Poster must be uploaded before completion",
        ));
    }
    if body.len() > 1_048_576 || body.len() < 4 || body[..3] != [255, 216, 255] {
        return Err(bad("A JPEG poster up to 1 MiB is required"));
    }
    let storage = s.storage.get()?;
    storage
        .s3
        .put_object()
        .bucket(&storage.bucket)
        .key(v.private_poster())
        .content_type("image/jpeg")
        .body(aws_sdk_s3::primitives::ByteStream::from(body))
        .send()
        .await
        .map_err(anyhow::Error::from)?;
    sqlx::query("UPDATE videos SET poster=1 WHERE id=? AND state='uploading'")
        .bind(id)
        .execute(&s.db)
        .await?;
    Ok(StatusCode::NO_CONTENT)
}
/// Return authenticated progress for a durable upload or background job.
///
/// # Errors
/// Returns authentication, expired/nonresumable-session, S3, or database errors.
#[utoipa::path(
    get,
    path = "/v1/admin/uploads/{id}",
    params(("id" = String, Path)),
    responses((status = 200, body = Upload)),
    security(("session" = [])),
)]
pub async fn status(
    State(s): State<AppState>,
    _admin: Admin,
    Path(id): Path<String>,
) -> Result<Json<Upload>> {
    let r = record(&s, &id).await?;
    let v = videos::get(&s, &r.video_id).await?;
    if r.state != "uploading" || r.expires_at <= now() {
        return Err(bad("Upload no longer resumable"));
    }
    let parts = s
        .storage
        .get()?
        .s3
        .list_parts()
        .bucket(&s.storage.get()?.bucket)
        .key(v.private_source())
        .upload_id(&r.upload_id)
        .max_parts(128)
        .send()
        .await
        .map_err(anyhow::Error::from)?
        .parts()
        .iter()
        .map(|p| UploadedPart {
            number: p.part_number.unwrap_or(0),
            size: p.size.unwrap_or(0),
            checksum: p.checksum_sha256.clone(),
        })
        .collect();
    Ok(Json(Upload {
        id: r.id,
        video_id: r.video_id,
        name: v.name,
        part_size: PART_SIZE,
        part_count: i32::try_from((v.size + PART_SIZE - 1) / PART_SIZE)
            .map_err(|_| bad("Too many upload parts"))?,
        expires_at: r.expires_at,
        parts,
    }))
}
